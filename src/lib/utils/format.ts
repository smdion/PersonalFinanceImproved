/**
 * Strip trailing institution suffix from an account label.
 * e.g. "Alice 401k (Fidelity)" → "Alice 401k"
 *
 * Handles balanced parens only — won't strip if no closing paren at end.
 */
export function stripInstitutionSuffix(label: string): string {
  return label.replace(/\s*\([^)]*\)\s*$/, "").trim();
}

/**
 * Owner display name from a peopleMap: "Joint" for a null owner id. Throws when
 * the id is missing from the map (an orphan FK is a data-integrity error).
 */
export function personDisplayName(
  ownerPersonId: number | null | undefined,
  peopleMap: Map<number, string>,
): string {
  if (ownerPersonId == null) return "Joint";
  const name = peopleMap.get(ownerPersonId);
  if (name == null) {
    throw new Error(`people.id=${ownerPersonId} not found in peopleMap`);
  }
  return name;
}

// Glyphs of the "Ledgr Redacted" font (globals.css, generated by
// scripts/gen-redacted-font.py): digit-width scribbles, each a different
// crossed-out shape.
const SQUIGGLE_GLYPHS = [
  "\uE000",
  "\uE001",
  "\uE002",
  "\uE003",
  "\uE004",
  "\uE005",
  "\uE006",
  "\uE007",
];

/** @internal Matches a whole masked amount, for tests and leak checks. */
export const MASKED_AMOUNT_PATTERN = /^\$[\uE000-\uE007]+$/;

// Random per page load: a squiggle can't be mapped back to an amount from
// another session, yet stays stable within one so re-renders don't flicker.
const maskSalt = Math.floor(Math.random() * 0x100000000);

/**
 * Privacy-mode stand-in for an amount: "$" + 3–8 squiggles (2–3 if `compact`),
 * no "," or ".". Shape comes from a hash of `seed` and a per-load salt, never the
 * digits, so it hides magnitude while equal seeds look alike until reload.
 */
export function maskedAmount(seed: number | string, compact = false): string {
  // FNV-1a over the seed, then xorshift32 for the picks.
  let h = (2166136261 ^ maskSalt) >>> 0;
  for (const ch of String(seed)) {
    h = Math.imul(h ^ ch.charCodeAt(0), 16777619) >>> 0;
  }
  if (h === 0) h = 0x9e3779b9; // xorshift never leaves a zero state
  const next = () => {
    h ^= h << 13;
    h ^= h >>> 17;
    h ^= h << 5;
    h >>>= 0;
    return h;
  };
  const length = compact ? 2 + (next() % 2) : 3 + (next() % 6);
  let out = "$";
  for (let i = 0; i < length; i++) {
    out += SQUIGGLE_GLYPHS[next() % SQUIGGLE_GLYPHS.length];
  }
  return out;
}

// "$1,234.56", "-$500", "$1.5M", "$45k". The k/M/B suffix must end a word
// so "$500 Brokerage" doesn't swallow the "B".
const DOLLAR_AMOUNT_IN_TEXT = /-?\$\s?-?\d[\d,]*(?:\.\d+)?(?:[kKMB]\b)?/g;

/**
 * Masks every dollar amount in a pre-built sentence while privacy mode is on
 * (the engine stays pure and writes plain amounts); else returns `text` as is.
 */
export function maskAmountsInText(text: string): string {
  if (!isPrivacyMode()) return text;
  return text.replace(DOLLAR_AMOUNT_IN_TEXT, (m) => maskedAmount(m));
}

/**
 * Format a number as USD currency. Returns maskedAmount() in privacy mode
 * (sign included — a "-" next to the mask would still leak information).
 */
export function formatCurrency(value: number, decimals: 0 | 2 = 2): string {
  if (isPrivacyMode()) return maskedAmount(value.toFixed(decimals));
  return new Intl.NumberFormat("en-US", {
    style: "currency",
    currency: "USD",
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  }).format(value);
}

/** Items as a sentence list: "A", "A and B", "A, B and C". */
export function formatList(items: readonly string[]): string {
  if (items.length <= 1) return items[0] ?? "";
  return `${items.slice(0, -1).join(", ")} and ${items[items.length - 1]}`;
}

/** A savings rate, at the precision it's judged at (SAVINGS_RATE_DECIMALS). */
export function formatSavingsRate(value: number): string {
  return formatPercent(value, SAVINGS_RATE_DECIMALS);
}

/** formatDate's presets: "Jan 2025", "Jan 5, 2025", "January 5, 2025",
 *  "Jan 5", "Jan 5, 25", "Jan 5, 2025, 03:07 PM" (en-US). */
const DATE_PRESETS = {
  short: { month: "short", year: "numeric" },
  medium: { month: "short", day: "numeric", year: "numeric" },
  long: { month: "long", day: "numeric", year: "numeric" },
  monthDay: { month: "short", day: "numeric" },
  dayShortYear: { month: "short", day: "numeric", year: "2-digit" },
  dateTime: {
    month: "short",
    day: "numeric",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  },
} as const satisfies Record<string, Intl.DateTimeFormatOptions>;

/**
 * A date for display: a YYYY-MM-DD string (date-only), or a Date for a
 * timestamp. 'default' is "1/5/2025"; 'time' is "3:07 PM" in the
 * browser's locale (a clock readout); the rest are DATE_PRESETS.
 */
export function formatDate(
  value: string | Date,
  preset: keyof typeof DATE_PRESETS | "time" | "default" = "default",
): string {
  const date = typeof value === "string" ? parseLocalDateOnly(value) : value;
  if (preset === "time")
    return date.toLocaleTimeString(undefined, {
      hour: "numeric",
      minute: "2-digit",
    });
  if (preset === "default") return date.toLocaleDateString("en-US");
  return date.toLocaleDateString("en-US", DATE_PRESETS[preset]);
}

/**
 * Format a timestamp as a short relative-time label (e.g., "just now",
 * "12m ago", "3h ago"), falling back to `formatDate`'s "medium" preset once
 * it's more than a day old. Accepts an ISO string or Date.
 */
export function formatRelativeTime(value: string | Date): string {
  const date = typeof value === "string" ? new Date(value) : value;
  const seconds = Math.round((Date.now() - date.getTime()) / 1000);
  if (seconds < 60) return "just now";
  const minutes = Math.round(seconds / 60);
  if (minutes < 60) return `${minutes}m ago`;
  const hours = Math.round(minutes / 60);
  if (hours < 24) return `${hours}h ago`;
  return formatDate(date, "medium");
}

/**
 * Format a large currency value in compact form (e.g., 1500000 → "$1.5M", 45000 → "$45k").
 * Suitable for chart axes and summary displays where full precision isn't needed.
 * Returns a compact maskedAmount() in privacy mode.
 */
export function compactCurrency(value: number): string {
  if (isPrivacyMode()) return maskedAmount(value, true);
  const abs = Math.abs(value);
  const sign = value < 0 ? "-" : "";
  if (abs >= 1_000_000) return `${sign}$${(abs / 1_000_000).toFixed(1)}M`;
  if (abs >= 1_000) return `${sign}$${(abs / 1_000).toFixed(0)}k`;
  return `${sign}$${abs.toFixed(0)}`;
}

/**
 * Format a number with commas (e.g., 1234567 → "1,234,567").
 */
export function formatNumber(value: number, decimals = 0): string {
  return new Intl.NumberFormat("en-US", {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  }).format(value);
}
