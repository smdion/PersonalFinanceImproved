/**
 * What contributors see of the tax-data format, generated from the key
 * list (lib/config/tax-limit-keys.ts, which includes the account config's
 * `irsLimitKeys`): the JSON Schemas the tax-data files point to (editor
 * autocomplete and red squiggles — one for a year file, one for
 * `index.json`) and the key table in `tax-data/README.md`.
 * `pnpm tax-data:schema` writes them; a test fails when any is stale.
 */
import { TAX_LIMIT_KEYS } from "@/lib/config/tax-limit-keys";
import { REQUIRED_FILING_STATUSES } from "@/lib/config/tax-params";
import type { TaxDataFile } from "@/lib/db/reference-reconcile-core";

/** Where the generated schemas go (relative to the repo root). */
export const TAX_DATA_SCHEMA_DIR = "tax-data/schema";
const README_KEYS_BEGIN = "<!-- BEGIN:keys (pnpm tax-data:schema) -->";
const README_KEYS_END = "<!-- END:keys -->";

const KIND_TEXT = {
  indexed: "inflation-indexed",
  rate: "rate set by law",
  statutory: "fixed by law",
} as const;

const exception = {
  type: "object",
  description:
    "Outside the year-to-year bounds on purpose — say why and cite it.",
  required: ["reason", "source"],
  properties: {
    reason: { type: "string", minLength: 1 },
    source: { $ref: "#/$defs/source" },
  },
  additionalProperties: false,
};

/** A section's per-filing-status object (every status, nothing else). */
const byStatus = (item: object) => ({
  type: "object",
  required: [...REQUIRED_FILING_STATUSES],
  properties: Object.fromEntries(
    REQUIRED_FILING_STATUSES.map((s) => [s, item]),
  ),
  additionalProperties: false,
});

const section = (body: Record<string, object>, required: string[]) => ({
  type: "object",
  required: ["source", ...required],
  properties: {
    source: { $ref: "#/$defs/source" },
    notes: { type: "string" },
    ...body,
    supersedes: {
      description: "Values this section shipped with before (corrections).",
    },
    exception,
  },
  additionalProperties: false,
});

const GENERATED =
  "Generated by `pnpm tax-data:schema` from src/lib/config/tax-limit-keys.ts — don't edit by hand. Conventions: tax-data/README.md.";

/** `tax-data/us-federal/index.json`: the format and the data version. */
function buildIndexSchema(): object {
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    title: "Ledgr tax data — index",
    description: GENERATED,
    type: "object",
    required: ["formatVersion", "dataVersion"],
    properties: {
      $schema: { type: "string" },
      formatVersion: { const: 1 },
      dataVersion: {
        type: "integer",
        minimum: 1,
        description:
          "Bump by one on every change to any year file (installs take the higher number as newer).",
      },
    },
    additionalProperties: false,
  };
}

/** `tax-data/us-federal/YYYY.json`: one year's figures. */
function buildYearSchema(): object {
  const rate = { type: "number", minimum: 0, maximum: 1 };
  const money = { type: "number", minimum: 0 };
  const withholdingRow = {
    type: "object",
    required: ["threshold", "baseWithholding", "rate"],
    properties: { threshold: money, baseWithholding: money, rate },
    additionalProperties: false,
  };
  const limits = Object.fromEntries(
    TAX_LIMIT_KEYS.map((k) => [
      k.key,
      {
        $ref: "#/$defs/limit",
        description: `${k.label} (${k.group}; ${KIND_TEXT[k.kind]}, ${k.format})`,
      },
    ]),
  );
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    title: "Ledgr tax data — one year",
    description: GENERATED,
    type: "object",
    required: ["revision", "source", "sources", "limits", "withholding"],
    properties: {
      $schema: { type: "string" },
      revision: {
        type: "integer",
        minimum: 1,
        description: "Bump when this year's figures change.",
      },
      source: { $ref: "#/$defs/source" },
      notes: { type: "string" },
      sources: {
        type: "object",
        description: "Each citation the year uses → a link to it.",
        additionalProperties: { type: "string", pattern: "^https://" },
      },
      limits: {
        type: "object",
        properties: limits,
        additionalProperties: false,
      },
      withholding: section(
        {
          tables: byStatus({
            type: "object",
            required: ["standard", "checkbox"],
            properties: {
              standard: { type: "array", items: withholdingRow },
              checkbox: { type: "array", items: withholdingRow },
            },
            additionalProperties: false,
          }),
        },
        ["tables"],
      ),
      ltcg: section(
        {
          brackets: byStatus({
            type: "array",
            items: {
              type: "object",
              required: ["threshold", "rate"],
              properties: {
                threshold: {
                  type: ["number", "null"],
                  description: "null = the top bracket (no upper end).",
                },
                rate,
              },
              additionalProperties: false,
            },
          }),
        },
        ["brackets"],
      ),
      irmaa: section(
        {
          brackets: byStatus({
            type: "array",
            items: {
              type: "object",
              required: ["magiThreshold", "annualSurcharge"],
              properties: {
                magiThreshold: money,
                annualSurcharge: {
                  ...money,
                  description:
                    "Per person, a year: Part B + Part D adjustments × 12.",
                },
              },
              additionalProperties: false,
            },
          }),
        },
        ["brackets"],
      ),
      fpl: section(
        {
          amounts: {
            type: "object",
            required: ["1", "2", "3", "4", "5", "6", "7", "8"],
            propertyNames: { pattern: "^[1-8]$" },
            additionalProperties: money,
          },
        },
        ["amounts"],
      ),
    },
    additionalProperties: false,
    $defs: {
      source: {
        type: "string",
        minLength: 1,
        description:
          'One or more citations joined by "; " — each a key in the year\'s `sources`.',
      },
      limit: {
        type: "object",
        required: ["value", "source"],
        properties: {
          value: { type: "number" },
          source: { $ref: "#/$defs/source" },
          notes: {
            type: "string",
            description: "Plain words about the figure (not a citation).",
          },
          supersedes: {
            type: "array",
            items: { type: "number" },
            description: "Values this key shipped with before (corrections).",
          },
          exception,
        },
        additionalProperties: false,
      },
    },
  };
}

/** Every generated schema file: path under TAX_DATA_SCHEMA_DIR → content. */
export function buildTaxDataSchemas(): Record<string, object> {
  return {
    "index.schema.json": buildIndexSchema(),
    "year.schema.json": buildYearSchema(),
  };
}

/** The README's key table: every key with its name, kind and the
 *  document the latest year cites for it. */
export function buildKeyTable(file: TaxDataFile): string {
  const latest =
    file.years[String(Math.max(...Object.keys(file.years).map(Number)))]!;
  const rows = TAX_LIMIT_KEYS.map(
    (k) =>
      `| \`${k.key}\` | ${k.label} | ${k.group} | ${KIND_TEXT[k.kind]} | ${latest.limits[k.key]?.source ?? "—"} |`,
  );
  return [
    "| Key | Name | Settings card | Kind | Latest source |",
    "| --- | --- | --- | --- | --- |",
    ...rows,
  ].join("\n");
}

/** The README with its key table replaced (between the markers). */
export function withKeyTable(readme: string, table: string): string {
  const a = readme.indexOf(README_KEYS_BEGIN);
  const b = readme.indexOf(README_KEYS_END);
  if (a < 0 || b < a)
    throw new Error(
      `tax-data/README.md needs ${README_KEYS_BEGIN} … ${README_KEYS_END}`,
    );
  return `${readme.slice(0, a + README_KEYS_BEGIN.length)}\n\n${table}\n\n${readme.slice(b)}`;
}
