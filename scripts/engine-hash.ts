/**
 * Writes src/lib/generated/engine-hash.ts: a hash of every source file the
 * cached projections run (each file that writes projection_cache and the
 * Monte Carlo worker, with everything they import), folded to a positive 31-bit integer
 * for `projection_cache.engine_version`. Any change to that code gives a new
 * version, so cached rows from older code are never read.
 *
 * Usage:  pnpm engine-hash          (rewrite the file)
 *         pnpm engine-hash --check  (exit 1 if the file is stale)
 */
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = "src/lib/generated/engine-hash.ts";

const CACHE_MODULE = "src/server/helpers/projection-cache.ts";
const WORKER = "src/workers/monte-carlo-worker.ts";

/** Every src/ file that writes projection_cache, and the worker they run. */
function entryPoints(): string[] {
  const writers = fs
    .readdirSync(path.join(ROOT, "src"), { recursive: true, encoding: "utf8" })
    .map((f) => path.posix.join("src", f.split(path.sep).join("/")))
    .filter((f) => /\.tsx?$/.test(f) && f !== CACHE_MODULE)
    .filter((f) =>
      fs
        .readFileSync(path.join(ROOT, f), "utf8")
        .includes("writeProjectionCache("),
    );
  return [...writers.sort(), WORKER];
}

/** Every src/ file the entry points reach, sorted (packages excluded). */
async function closure(): Promise<string[]> {
  const result = await build({
    absWorkingDir: ROOT,
    entryPoints: entryPoints(),
    bundle: true,
    write: false,
    metafile: true,
    platform: "node",
    format: "esm",
    packages: "external",
    outdir: "out",
    logLevel: "silent",
  });
  return Object.keys(result.metafile.inputs)
    .filter((f) => f.startsWith("src/") && !f.startsWith("src/lib/generated/"))
    .sort();
}

/** sha256 over each file's path and bytes, folded to 1..2^31-1. */
function foldHash(files: { path: string; bytes: Buffer }[]): number {
  const h = createHash("sha256");
  for (const f of files) {
    h.update(f.path);
    h.update("\0");
    h.update(f.bytes);
    h.update("\0");
  }
  return h.digest().readUInt32BE(0) & 0x7fffffff || 1;
}

function render(hash: number, fileCount: number): string {
  return `// Generated by scripts/engine-hash.ts (pnpm engine-hash): do not edit.

/** projection_cache.engine_version: a hash of the ${fileCount} source files
 *  the cached projections run. */
export const ENGINE_HASH = ${hash};
`;
}

async function main(): Promise<void> {
  const files = await closure();
  const hash = foldHash(
    files.map((p) => ({ path: p, bytes: fs.readFileSync(path.join(ROOT, p)) })),
  );
  const next = render(hash, files.length);
  const outPath = path.join(ROOT, OUT);
  const current = fs.existsSync(outPath)
    ? fs.readFileSync(outPath, "utf8")
    : "";
  if (process.argv.includes("--check")) {
    if (current !== next) {
      console.error(
        `${OUT} is stale (engine code changed): run 'pnpm engine-hash' and commit the result.`,
      );
      process.exit(1);
    }
    console.log(`${OUT} is current (${files.length} files).`);
    return;
  }
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, next);
  console.log(`Wrote ${OUT}: ${hash} (${files.length} files).`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
